const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const model = {};
vm.createContext(model);
vm.runInContext(fs.readFileSync(__dirname + '/FleetModel.js', 'utf8'), model);
const mouse = {id:'mouse', name:'Aerox', kind:'mouse', state:'connected', wireless:true, battery:65, charging:false};
let state = model.advance(null, [mouse]);
assert.equal(state.events.length, 0, 'startup is silent');
state = model.advance(state, [{...mouse,state:'offline'}]);
assert.equal(state.events[0].type, 'disconnected');
state = model.advance(state, [mouse]);
assert.equal(state.events[0].type, 'connected');
state = model.advance(state, [{...mouse,battery:20}]);
assert.equal(state.events[0].type, 'low');
state = model.advance(state, [{...mouse,battery:19}]);
assert.equal(state.events.length, 0, 'low alert deduplicated');
state = model.advance(state, [{...mouse,battery:50,charging:true}]);
state = model.advance(state, [{...mouse,battery:10}]);
assert.equal(state.events[0].type, 'low', 'charging rearms low alert');
state = model.advance(state, []);
assert.equal(state.events[0].type, 'disconnected', 'USB unplug');
state = model.advance(state, [mouse]);
assert.equal(state.events[0].type, 'connected', 'USB replug');
const wired = {...mouse,id:'keyboard',wireless:false,battery:-1};
state = model.advance(state, [mouse,wired]);
assert.equal(state.events.length, 0, 'wired device connect is silent');
state = model.advance(state, [{...mouse,state:'error'},wired]);
assert.equal(state.events.length, 0, 'read error is not a disconnect');
assert.equal(model.safeText('<img src=x>&'), '‹img src=x›＆');
assert.equal(model.deviceLabel({...mouse,battery:-1}), '—');
assert.equal(model.deviceLabel(mouse), '65%');
assert.equal(model.deviceLabel({...mouse,state:'offline'}), '—');
assert.equal(model.deviceLabel(wired), '');
assert.ok(!fs.readFileSync(__dirname + '/SteelSeriesService.qml', 'utf8').includes('property var data:'), 'Do not shadow Item.data');
assert.ok(fs.readFileSync(__dirname + '/Panel.qml', 'utf8').includes('MouseIcon'), 'Mouse uses a vector icon, not a missing font glyph');
console.log('Fleet UI model assertions passed');
